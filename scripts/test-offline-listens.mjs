// Synthetic PostgreSQL only. A fresh schema is removed even after a failed check.
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {readFile,readdir} from 'node:fs/promises';
import pg from 'pg';
import {createDatabase} from '../apps/api/dist/db/database.js';
import {importOfflineListens} from '../apps/api/dist/activity/offline-listens.js';
import {encodeTrackReference} from '../apps/api/dist/music-source/track-reference.js';
const url=new URL(process.env.HIRMOS_TEST_DATABASE_URL??'');
assert(['127.0.0.1','localhost'].includes(url.hostname)&&url.pathname==='/hirmos_core_test');
const admin=new pg.Client({connectionString:url.href});await admin.connect();
const schema=`hirmos_offline_report_${randomUUID().replaceAll('-','')}`;
await admin.query(`CREATE SCHEMA ${schema}`);
url.searchParams.set('options',`-c search_path=${schema} -c statement_timeout=10000`);
const db=createDatabase(url.href);let checks=0;
const pass=label=>{console.log(`PASS ${label}`);checks++;};
try{
  for(const file of (await readdir(new URL('../database/migrations/',import.meta.url))).filter(f=>f.endsWith('.sql')).sort())
    await db.query(await readFile(new URL(`../database/migrations/${file}`,import.meta.url),'utf8'));
  const users=(await db.query("INSERT INTO users(email,display_name,role) VALUES('a@example.test','A','user'),('b@example.test','B','user') RETURNING id")).rows.map(r=>r.id);
  const source=(await db.query("INSERT INTO music_sources(name,adapter_type,base_url,credential_ciphertext,encryption_key_version) VALUES('Synthetic','navidrome','https://music.example.test',decode('00','hex'),1) RETURNING id")).rows[0].id;
  await db.query("INSERT INTO catalog_tracks(source_id,remote_track_id,title,artist_name,album_name) VALUES($1,'track','Synthetic','Artist','Album')",[source]);
  const base={id:randomUUID(),executionId:randomUUID(),reference:encodeTrackReference(source,'track'),startedAt:'2026-10-10T23:59:58.000Z',at:'2026-10-10T23:59:59.999Z',heardMs:2000};
  const later={...base,id:randomUUID(),at:'2026-10-11T00:00:04.999Z',heardMs:5000};
  const importRows=(reports,user=users[0])=>importOfflineListens(db,user,reports,Date.parse('2026-10-13T00:00:00Z'));
  const stats=async(user=users[0])=>(await db.query("SELECT * FROM user_track_stats WHERE user_id=$1 AND remote_track_id='track'",[user])).rows[0];
  await Promise.all([importRows([later,base]),importRows([base,later]),importRows([later])]);
  assert.equal((await stats()).play_starts,1);assert.equal(Number((await stats()).listened_ms),7000);
  pass('concurrent, repeated and out-of-order imports count each execution and chunk exactly once');
  const days=(await db.query('SELECT stat_date::text,play_starts,listened_ms FROM user_track_daily_stats WHERE user_id=$1 ORDER BY stat_date',[users[0]])).rows;
  assert.deepEqual(days,[{stat_date:'2026-10-10',play_starts:1,listened_ms:'2000'},{stat_date:'2026-10-11',play_starts:0,listened_ms:'5000'}]);
  assert.equal((await stats()).last_played_at.toISOString(),later.at);
  pass('actual UTC listening dates, not upload time, drive daily and recent stats');
  await db.query('UPDATE user_track_stats SET last_position_ms=42000,last_observed_at=$2,last_played_at=$2 WHERE user_id=$1',[users[0],'2026-10-12T12:00:00Z']);
  await importRows([{...later,id:randomUUID(),at:'2026-10-11T00:00:09.999Z'}]);
  assert.equal((await stats()).last_position_ms,42000);assert.equal((await stats()).last_observed_at.toISOString(),'2026-10-12T12:00:00.000Z');
  assert.equal((await stats()).last_played_at.toISOString(),'2026-10-12T12:00:00.000Z');
  assert.equal(Number((await db.query('SELECT count(*) AS n FROM playback_sessions')).rows[0].n),0);
  assert.equal(Number((await db.query('SELECT count(*) AS n FROM listen_events')).rows[0].n),0);
  pass('import cannot change online position, lease, queue, newer recent dates or manufacture player events');
  const conflict=await importRows([{...base,heardMs:1000},{...base,id:randomUUID(),startedAt:'2026-10-10T23:59:57.000Z'}]);
  assert.deepEqual(conflict.rejected.map(r=>r.code),['ID_CONFLICT','ID_CONFLICT']);
  const missing={...base,id:randomUUID(),executionId:randomUUID(),reference:encodeTrackReference(source,'missing')};
  assert.equal((await importRows([missing])).rejected[0].code,'UNKNOWN_TRACK');
  await db.query("INSERT INTO catalog_tracks(source_id,remote_track_id,title,artist_name,album_name) VALUES($1,'missing','Found','Artist','Album')",[source]);
  assert.deepEqual((await importRows([missing])).accepted,[missing.id]);
  pass('changed payloads are rejected; temporarily unknown catalog tracks remain retryable');
  await importRows([base],users[1]);assert.equal((await stats(users[1])).play_starts,1);assert.equal(Number((await stats(users[1])).listened_ms),2000);
  pass('same report identifiers from different authenticated accounts remain isolated');
  const before=await stats();
  await db.query(`CREATE FUNCTION reject_offline_receipt() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'synthetic'; END $$;
    CREATE TRIGGER reject_offline_receipt BEFORE INSERT ON offline_listen_receipts FOR EACH ROW EXECUTE FUNCTION reject_offline_receipt()`);
  const failed={...later,id:randomUUID(),executionId:randomUUID()};await assert.rejects(importRows([failed]));
  assert.deepEqual(await stats(),before);
  assert.equal(Number((await db.query('SELECT count(*) AS n FROM offline_listen_executions WHERE id=$1',[failed.executionId])).rows[0].n),0);
  await db.query('DROP TRIGGER reject_offline_receipt ON offline_listen_receipts; DROP FUNCTION reject_offline_receipt()');
  await importRows([failed]);assert.equal((await stats()).play_starts,before.play_starts+1);
  pass('failure rolls back execution, receipt and stats together; retry can safely commit');
  console.log(`${checks} offline report integration groups passed`);
}finally{await db.close();await admin.query(`DROP SCHEMA ${schema} CASCADE`);await admin.end();}
